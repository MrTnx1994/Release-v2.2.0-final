/**
 * Dynamically computes current release month & year based on today's Shamsi date (e.g. مرداد ۱۴۰۵)
 */
export function getAppReleaseDate(): string {
  const today = getTodayShamsi();
  return `${today.monthName} ${today.year}`;
}

export const APP_RELEASE_DATE = getAppReleaseDate();

