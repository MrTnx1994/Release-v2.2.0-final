export const OFFICIAL_HOLIDAYS: string[] = Object.keys(HOLIDAY_DICTIONARY);

export function isOfficialHoliday(dateStr: string): boolean {
  if (!dateStr) return false;
  // Normalize formatted date YYYY/MM/DD
  const parts = dateStr.split("/").map((p) => p.padStart(2, "0"));
  if (parts.length === 3) {
    const normalized = `${parts[0]}/${parts[1]}/${parts[2]}`;
    return Boolean(HOLIDAY_DICTIONARY[normalized]);
  }
  return Boolean(HOLIDAY_DICTIONARY[dateStr]);
}

export function getHolidayTitle(dateStr: string): string | null {
  if (!dateStr) return null;
  const parts = dateStr.split("/").map((p) => p.padStart(2, "0"));
  if (parts.length === 3) {
    const normalized = `${parts[0]}/${parts[1]}/${parts[2]}`;
    return HOLIDAY_DICTIONARY[normalized] || null;
  }
  return HOLIDAY_DICTIONARY[dateStr] || null;
}

let isFetchingHolidays = false;
export async function fetchHolidaysFromServer() {
  if (isFetchingHolidays) return;
  isFetchingHolidays = true;
  try {
    const res = await fetch('/api/holidays');
    if (res.ok) {
      const data = await res.json();
      if (data && typeof data === 'object') {
        Object.assign(HOLIDAY_DICTIONARY, data);
      }
    }
  } catch (e) {
    console.error("Failed to fetch holidays from server:", e);
  } finally {
    isFetchingHolidays = false;
  }
}

